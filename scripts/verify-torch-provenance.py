#!/usr/bin/env python3
"""Verify the installed CPU Torch files, frozen upstream wheel and advisories.

Run with the application Python interpreter. The normalized upstream advisory
query supplements pip-audit's unsupported local-version lookup; it does not
claim coverage of CPU-build-only vulnerabilities.
"""
import argparse
import base64
import csv
import hashlib
import importlib.metadata
import json
from pathlib import Path
import sys
import sysconfig
import tomllib
import urllib.parse
import urllib.request
from datetime import datetime, timezone


def verify_record(distribution):
    failures, checked = [], 0
    for name, digest, size in csv.reader(distribution.read_text("RECORD").splitlines()):
        if not digest:
            continue  # RECORD itself and generated bytecode have no signed digest.
        algorithm, encoded = digest.split("=", 1)
        file = Path(distribution.locate_file(name))
        if algorithm != "sha256" or not file.is_file():
            failures.append(name)
            continue
        with file.open("rb") as source:
            actual = hashlib.file_digest(source, "sha256").digest()
        if base64.urlsafe_b64encode(actual).decode().rstrip("=") != encoded or file.stat().st_size != int(size):
            failures.append(name)
        checked += 1
    return checked, failures


def locked_wheel(lock, version):
    package = next(p for p in lock["package"] if p["name"] == "torch" and p["version"] == version)
    if package["source"] != {"registry": "https://download.pytorch.org/whl/cpu"}:
        raise ValueError("Torch is not locked to the official CPU index")
    abi = f"cp{sys.version_info.major}{sys.version_info.minor}"
    platform = sysconfig.get_platform().replace("-", "_")
    arch = "aarch64" if platform.endswith("aarch64") else "x86_64" if platform.endswith("x86_64") else None
    if not arch or sys.platform != "linux":
        raise ValueError("This supplemental gate supports the Linux CPU runtime only")
    wheels = [w for w in package["wheels"] if f"-{abi}-{abi}-manylinux_2_28_{arch}.whl" in w["url"]]
    if len(wheels) != 1:
        raise ValueError("No unique frozen CPU wheel for this interpreter")
    wheel = wheels[0]
    url = urllib.parse.urlsplit(wheel["url"])
    if url.scheme != "https" or url.hostname not in {"download.pytorch.org", "download-r2.pytorch.org"}:
        raise ValueError("Unexpected upstream wheel origin")
    return wheel


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cache", type=Path, required=True, help="Outside-checkout verified wheel cache")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    lock = tomllib.loads((root / "external/maxcore/artifacts/ai-training-server/uv.lock").read_text())
    distribution = importlib.metadata.distribution("torch")
    version = distribution.version
    wheel = locked_wheel(lock, version)
    args.cache.mkdir(parents=True, exist_ok=True)
    archive = args.cache / Path(urllib.parse.unquote(urllib.parse.urlsplit(wheel["url"]).path)).name
    if not archive.exists():
        temporary = archive.with_suffix(".partial")
        try:
            with urllib.request.urlopen(wheel["url"], timeout=60) as source, temporary.open("wb") as target:
                while block := source.read(1024 * 1024):
                    target.write(block)
            temporary.replace(archive)
        finally:
            temporary.unlink(missing_ok=True)
    with archive.open("rb") as source:
        checksum = hashlib.file_digest(source, "sha256").hexdigest()
    if wheel["hash"] != f"sha256:{checksum}":
        raise ValueError("Frozen upstream Torch wheel checksum mismatch")
    checked, failures = verify_record(distribution)
    # Compare installed RECORD to the verified upstream archive, so locally
    # rewritten RECORD hashes cannot conceal modifications.
    import zipfile
    with zipfile.ZipFile(archive) as upstream:
        records = [n for n in upstream.namelist() if n.endswith(".dist-info/RECORD")]
        if len(records) != 1:
            raise ValueError("Invalid upstream RECORD")
        upstream_records = {row[0]: row[1:] for row in csv.reader(upstream.read(records[0]).decode().splitlines()) if row[1]}
    installed_records = {row[0]: row[1:] for row in csv.reader(distribution.read_text("RECORD").splitlines()) if row[1]}
    for name, record in upstream_records.items():
        if installed_records.get(name) != record:
            failures.append(f"upstream RECORD mismatch: {name}")
    query = {"package": {"name": "torch", "ecosystem": "PyPI"}, "version": version.split("+", 1)[0]}
    request = urllib.request.Request("https://api.osv.dev/v1/query", data=json.dumps(query).encode(), headers={"Content-Type": "application/json"})
    with urllib.request.urlopen(request, timeout=30) as response:
        advisories = json.load(response)
    report = {"testedAt": datetime.now(timezone.utc).isoformat(), "installedVersion": version,
              "wheelOrigin": wheel["url"], "frozenWheelSha256": checksum,
              "installedFilesVerified": checked, "integrityFailures": failures,
              "advisoryQuery": query, "advisories": advisories.get("vulns", []),
              "coverage": "Official CPU artifact integrity plus upstream Torch advisory version; CPU-only advisory coverage is not guaranteed"}
    report["pass"] = checked > 0 and not failures and not report["advisories"]
    print(json.dumps(report, indent=2))
    return 0 if report["pass"] else 1


if __name__ == "__main__":
    sys.exit(main())
