import test from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { spawnSync } from "node:child_process";

const helper = path.resolve("script/lib/copy-diffusion-source.py");

function fixture(t) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "diffusion-copy-"));
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  const source = path.join(root, "server/services/diffusion");
  const destination = path.join(root, "services/diffusion");
  fs.mkdirSync(path.join(source, "advanced_memory", "nested"), { recursive: true });
  fs.mkdirSync(path.join(source, "worker", "__pycache__"), { recursive: true });
  fs.writeFileSync(path.join(source, "worker.py"), "print('real worker')\n");
  fs.writeFileSync(path.join(source, "advanced_memory/nested/shard.npz"), "generated shard");
  fs.writeFileSync(path.join(source, "worker/__pycache__/worker.pyc"), "generated bytecode");
  fs.writeFileSync(path.join(source, "worker/cache.npz"), "generated array shard");
  return { root, source, destination };
}

test("diffusion staging excludes generated shards before copy and preserves the source tree", t => {
  const { source, destination } = fixture(t);
  const result = spawnSync("python3", [helper, source, destination], {
    encoding: "utf8",
    timeout: 15_000,
  });
  assert.equal(result.status, 0, result.stderr);
  assert.match(result.stdout, /generated shards and bytecode excluded/);
  assert.equal(fs.readFileSync(path.join(destination, "worker.py"), "utf8"), "print('real worker')\n");
  assert.equal(fs.existsSync(path.join(destination, "advanced_memory")), false);
  assert.equal(fs.existsSync(path.join(destination, "worker/__pycache__")), false);
  assert.equal(fs.existsSync(path.join(destination, "worker/cache.npz")), false);
  assert.equal(fs.existsSync(path.join(source, "advanced_memory/nested/shard.npz")), true);
  assert.equal(fs.existsSync(path.join(source, "worker/__pycache__/worker.pyc")), true);
});

test("failed diffusion staging leaves the existing runtime copy intact", t => {
  const { source, destination } = fixture(t);
  fs.mkdirSync(destination, { recursive: true });
  fs.writeFileSync(path.join(destination, "existing.py"), "old verified runtime");
  const result = spawnSync("python3", [helper, path.join(source, "missing"), destination], {
    encoding: "utf8",
    timeout: 15_000,
  });
  assert.notEqual(result.status, 0);
  assert.equal(fs.readFileSync(path.join(destination, "existing.py"), "utf8"), "old verified runtime");
});
